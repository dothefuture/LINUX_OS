#!/bin/bash
# Задача 5. Значения по умолчанию

greet() {
    # ${1-Гость}  — только если аргумент НЕ передан (unset)
    # ${name:-Незнакомец} — если пустая строка
    local name
    name=${1-Гость}
    name=${name:-Незнакомец}
    echo "Привет, $name"
}

echo "=== без аргумента → Гость ==="
greet

echo "=== пустая строка → Незнакомец ==="
greet ""

echo "=== с именем ==="
greet "Анна"

echo "=== ${1:?Имя обязательно} ==="
require_name() {
    local name="${1:?Имя обязательно}"
    echo "Имя: $name"
}

require_name "Иван"

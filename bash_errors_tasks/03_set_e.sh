#!/bin/bash
# Задача 3. set -e и его ловушка

set -e

echo "Перед false"
false
# Эта строка не выполнится, потому что set -e прерывает скрипт при ненулевом коде
echo "После false — не должно появиться"

# Почему if false; then ...; fi НЕ прерывает скрипт при set -e:
# set -e НЕ срабатывает на команды внутри условия if/while/until и слева от &&/||.
# Там ненулевой код — часть проверки условия, а не «ошибка скрипта».
# Пример (не прервёт):
# if false; then
#     echo "ветка then"
# fi
# echo "скрипт продолжается"
#!/bin/bash
# Задача 2. Аргументы и валидация
# Использование: ./02_args_validate.sh <файл> <число>

if [ $# -lt 2 ]; then
    echo "Использование: $0 <файл> <число>" >&2
    exit 1
fi

file=$1
num=$2

if ! [[ "$num" =~ ^[0-9]+$ ]]; then
    echo "Второй аргумент должен быть числом" >&2
    exit 2
fi

echo "OK"